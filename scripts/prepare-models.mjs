// Prepares the Figma exports (public/models/*.svg) for the landing scene.
// Usage: node scripts/prepare-models.mjs
//  - cosmo.svg      -> public/models/cosmo-robot.svg (speech bubble removed, cropped to the robot)
//  - astronaut.svg  -> src/components/landing/astronautSvg.ts (inline string so each rig layer can animate)
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";

const cosmo = readFileSync("public/models/cosmo.svg", "utf8")
  .replace(/<rect x="818" y="22"[^>]*\/>\s*<path d="M848 134L888 140[^>]*\/>\s*(<circle[^>]*\/>\s*){3}/, "")
  .replace(/<svg width="1116" height="1410" viewBox="0 0 1116 1410"/, '<svg viewBox="200 90 720 1320"');
writeFileSync("public/models/cosmo-robot.svg", cosmo);

const astro = readFileSync("public/models/astronaut.svg", "utf8")
  .replace(/<rect width="1447" height="1857" fill="#F5F5F5"\/>\s*/, "")
  .replace(/<svg width="1447" height="1857"/, '<svg class="astro-svg" role="img" aria-label="Astronaut with a wrist device projecting the COSMO hologram"')
  // ids with spaces and mis-encoded middle dots -> clean, prefixed ids
  .replace(/id="([^"]*)"/g, (_, id) => `id="astro-${id.replace(/&#194;&#183;/g, "").replace(/[^A-Za-z0-9_-]+/g, "-").replace(/-+$/,"")}"`)
  .replace(/url\(#([^)]*)\)/g, (_, id) => `url(#astro-${id})`)
  .replace(/clip-path="url\(#astro-clip0_0_1\)"/, "");
mkdirSync("src/components/landing", { recursive: true });
writeFileSync(
  "src/components/landing/astronautSvg.ts",
  `// Generated by scripts/prepare-models.mjs from the team's Figma file (Cosmo AI, "Astronaut parts").\nexport const ASTRONAUT_SVG = ${JSON.stringify(astro)};\n`,
);
console.log("cosmo-robot.svg", cosmo.length, "astronautSvg.ts", astro.length);
